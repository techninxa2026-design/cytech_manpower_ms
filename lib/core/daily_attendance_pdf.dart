import 'dart:io';
import 'dart:typed_data';
import 'package:flutter/services.dart' show rootBundle;
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:image/image.dart' as img;
import 'app_store.dart';
import 'payroll.dart';

/// Read-only daily register. Never modifies attendance or payroll.
class DailyAttendancePdf {
  DailyAttendancePdf._();

  static List<AttendanceReport> records(AppStore store, String date,{String? groupId}){
    if(!store.signedIn||!store.isAdmin) throw StateError('Admin only');
    final reports=store.attendance.where((a)=>a.date==date&&
      (groupId==null||a.groupId==groupId)&&store.isCurrentAttendance(a)).toList();
    reports.sort((a,b)=>groupName(store,a).compareTo(groupName(store,b)));
    return reports;
  }

  static String groupName(AppStore store,AttendanceReport a){
    if(a.groupName.isNotEmpty)return a.groupName;
    for(final g in store.groups){if(g.id==a.groupId)return g.name;}
    return 'Archived group';
  }

  static String filename(String date)=>'Cytech_Attendance_'+date+'.pdf';
  static String _time(String value)=>value.replaceFirst('T',' ').split('.').first;

  static Future<Uint8List> build(AppStore store,String date,{
    String? groupId,bool includePermits=true})async{
    final rows=records(store,date,groupId:groupId);
    if(rows.isEmpty)throw StateError('No attendance records for this date');
    final doc=pw.Document(title:'Cytech Daily Attendance - '+date,author:'Cytech Engineering');
    final navy=PdfColor.fromHex('#071A2E'),orange=PdfColor.fromHex('#FC4B09'),
      muted=PdfColor.fromHex('#657482'),pale=PdfColor.fromHex('#F1F5F8');
    final body=pw.TextStyle(color:navy,fontSize:10);
    final small=pw.TextStyle(color:muted,fontSize:9);
    final bold=pw.TextStyle(color:navy,fontSize:11,fontWeight:pw.FontWeight.bold);
    pw.MemoryImage? logo;
    try{final data=await rootBundle.load('assets/brand/cytech_logo.png');
      logo=pw.MemoryImage(data.buffer.asUint8List(data.offsetInBytes,data.lengthInBytes));
    }catch(_){ /* Wordmark remains available. */ }
    final permits=<String,pw.MemoryImage>{};
    if(includePermits){
      for(final a in rows){
        final proof=a.permit;
        if(proof==null||!proof.isValid)continue;
        try{
          final bytes=await File(proof.imagePath).readAsBytes();
          final decoded=img.decodeImage(bytes);
          if(decoded!=null){
            permits[a.id]=pw.MemoryImage(img.encodeJpg(decoded,quality:92));
          }
        }catch(_){ /* Missing or damaged attachment is disclosed in register. */ }
      }
    }
    if(!store.signedIn||!store.isAdmin)throw StateError('Admin only');
    final logoImage=logo;
    pw.Widget header(String title)=>pw.Container(
      padding:const pw.EdgeInsets.only(bottom:10),
      decoration:pw.BoxDecoration(border:pw.Border(bottom:pw.BorderSide(color:orange,width:2))),
      child:pw.Row(children:[
        if(logoImage!=null)...[pw.Image(logoImage,width:34,height:34),pw.SizedBox(width:10)],
        pw.Expanded(child:pw.Column(crossAxisAlignment:pw.CrossAxisAlignment.start,children:[
          pw.Text('CYTECH ENGINEERING',style:pw.TextStyle(color:navy,fontSize:17,fontWeight:pw.FontWeight.bold)),
          pw.Text(title,style:pw.TextStyle(color:orange,fontSize:9,fontWeight:pw.FontWeight.bold)),
        ])),
        pw.Text(date,style:bold),
      ]));
    pw.Widget stat(String value,String label)=>pw.Expanded(child:pw.Padding(
      padding:const pw.EdgeInsets.all(8),child:pw.Column(
        crossAxisAlignment:pw.CrossAxisAlignment.start,children:[
          pw.Text(value,style:pw.TextStyle(color:PdfColors.white,fontSize:19,fontWeight:pw.FontWeight.bold)),
          pw.SizedBox(height:5),
          pw.Text(label,style:pw.TextStyle(color:PdfColors.grey300,fontSize:8)),
        ])));
    final present=rows.fold<int>(0,(s,a)=>s+a.presentCount);
    final absent=rows.fold<int>(0,(s,a)=>s+a.absentCount);
    final hours=rows.fold<double>(0,(s,a)=>s+a.totalHours);
    final ot=rows.fold<double>(0,(s,a)=>s+a.totalOvertime);
    doc.addPage(pw.MultiPage(pageFormat:PdfPageFormat.a4,
      margin:const pw.EdgeInsets.all(34),maxPages:1000,
      header:(_)=>header('DAILY ATTENDANCE REGISTER'),
      footer:(c)=>pw.Row(mainAxisAlignment:pw.MainAxisAlignment.spaceBetween,children:[
        pw.Text('Local attendance record | Current reports only',style:small),
        pw.Text('Page '+c.pageNumber.toString(),style:small),
      ]),
      build:(_)=>[
        pw.SizedBox(height:18),
        pw.Text('Daily attendance report',style:pw.TextStyle(color:navy,fontSize:23,fontWeight:pw.FontWeight.bold)),
        pw.SizedBox(height:5),
        pw.Text('Date: '+date+'  |  Scope: '+(groupId==null?'All groups':groupName(store,rows.first)),style:body),
        pw.Text('Generated by '+store.me.name+' on '+_time(DateTime.now().toIso8601String()),style:small),
        pw.SizedBox(height:14),
        pw.Container(decoration:pw.BoxDecoration(color:navy,borderRadius:pw.BorderRadius.circular(8)),
          child:pw.Row(children:[
            stat(rows.length.toString(),'GROUPS'),stat(present.toString(),'PRESENT*'),
            stat(absent.toString(),'ABSENT*'),stat(hourLabel(hours)+'h','WORKED'),stat(hourLabel(ot)+'h','OVERTIME'),
          ])),
        pw.SizedBox(height:7),
        pw.Text('*Counts are worker-group entries, not unique people. Latest report per group/date only.',style:small),
        for(final a in rows)...[
          pw.SizedBox(height:18),
          pw.Text(groupName(store,a),style:pw.TextStyle(color:navy,fontSize:15,fontWeight:pw.FontWeight.bold)),
          pw.SizedBox(height:5),
          pw.Text('Published by '+store.person(a.authorId).name+' | '+_time(a.createdAt),style:small),
          pw.Text('Work Permit: '+(a.permit?.code??'Legacy - not recorded')+
            (a.permit==null?'':!includePermits?' (photo excluded by selection)':
              permits.containsKey(a.id)?' (photo in appendix)':' (photo unavailable or unreadable)'),style:body),
          pw.SizedBox(height:5),
          pw.Text(a.approvals.isEmpty?'Engineer approval: Not yet approved':
            'Engineer approval: ENGINEER APPROVED',style:bold),
          for(final approval in a.approvals.values)
            pw.Text(approval.engineerName+' | '+_time(approval.approvedAt),style:small),
          pw.Text('Pending assigned engineers: '+(
            store.assignedEngineers(a).where((id)=>!a.approvals.containsKey(id)&&id!=a.authorId)
              .map((id)=>store.person(id).name).join(', ').isEmpty?'None':
            store.assignedEngineers(a).where((id)=>!a.approvals.containsKey(id)&&id!=a.authorId)
              .map((id)=>store.person(id).name).join(', ')),style:small),
          pw.SizedBox(height:9),
          pw.TableHelper.fromTextArray(
            headers:['No.','Worker','Status','Regular (h)','OT (h)','Total (h)'],
            data:a.present.entries.toList().asMap().entries.map((e){
              final id=e.value.key,h=a.hoursFor(id),o=a.overtimeFor(id);
              return [(e.key+1).toString(),store.person(id).name+'\n@'+store.person(id).username,
                e.value.value?'Present':'Absent',hourLabel(h-o),hourLabel(o),hourLabel(h)];
            }).toList(),
            headerDecoration:pw.BoxDecoration(color:navy),
            headerStyle:pw.TextStyle(color:PdfColors.white,fontSize:9,fontWeight:pw.FontWeight.bold),
            cellStyle:pw.TextStyle(color:navy,fontSize:9),
            cellPadding:const pw.EdgeInsets.all(6),
            oddRowDecoration:pw.BoxDecoration(color:pale),
            border:pw.TableBorder.symmetric(inside:pw.BorderSide(color:PdfColors.grey300)),
          ),
          pw.SizedBox(height:7),
          pw.Text('Present: '+a.presentCount.toString()+'  |  Absent: '+a.absentCount.toString()+
            '  |  Regular: '+hourLabel(a.totalHours-a.totalOvertime)+'h  |  OT: '+
            hourLabel(a.totalOvertime)+'h  |  Total: '+hourLabel(a.totalHours)+'h',style:bold),
          pw.Divider(color:PdfColors.grey300),
        ],
        pw.SizedBox(height:12),
        pw.Text('Prepared by: ____________________     Reviewed by: ____________________',style:body),
        pw.SizedBox(height:8),
        pw.Text('Engineer approval refers to the recorded attendance review, not a work permit authorization.',style:small),
      ]));
    for(final a in rows){
      final photo=permits[a.id];
      if(photo==null)continue;
      doc.addPage(pw.Page(pageFormat:PdfPageFormat.a4,margin:const pw.EdgeInsets.all(32),
        build:(_)=>pw.Column(crossAxisAlignment:pw.CrossAxisAlignment.start,children:[
          header('WORK PERMIT ATTACHMENT'),
          pw.SizedBox(height:12),
          pw.Text(groupName(store,a)+' | PTW '+a.permit!.code,style:bold),
          pw.Text('Scan timestamp: '+_time(a.permit!.scannedAt),style:small),
          pw.SizedBox(height:10),
          pw.Expanded(child:pw.Center(child:pw.Image(photo,fit:pw.BoxFit.contain))),
        ])));
    }
    return doc.save();
  }
}
